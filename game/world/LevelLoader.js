  static getBiome(levelIndex) {
      const idx = ((levelIndex - 1) % 120) + 1;
      if (idx <= 8) return 'workshop';        // M1 - M8: Warm cozy oak wood workshop
      if (idx <= 16) return 'desert';         // M9 - M16: Sandstone ruins & terracotta
      if (idx <= 24) return 'cyber';          // M17 - M24: Neon cyberpunk grid & chrome
      if (idx <= 32) return 'arctic';         // M25 - M32: Glacial crystalline ice & snow
      if (idx <= 40) return 'volcano';        // M33 - M40: Magma crucible & volcanic basalt
      if (idx <= 48) return 'jungle';         // M41 - M48: Emerald Jungle & Ancient Temples
      if (idx <= 56) return 'sunset_city';    // M49 - M56: Sunset/Night Metropolis
      if (idx <= 64) return 'matsuri';        // M57 - M64: Japanese Festival with String Lights
      if (idx <= 72) return 'tropical_island';// M65 - M72: Tropical Paradise Island
      if (idx <= 80) return 'night_stealth';  // M73 - M80: Night Stealth Operations
      if (idx <= 88) return 'cyber';          // M81 - M88: Portal & Laser Labs
      if (idx <= 96) return 'volcano';        // M89 - M96: Demolition & Pyrotechnic Arenas
      if (idx <= 104) return 'arctic';        // M97 - M104: Centurion Colosseum & Mirror Halls
      if (idx <= 112) return 'matsuri';       // M105 - M112: Urban Chaos & Hanabi Mega-Blast
      return 'night_stealth';                 // M113 - M120: Special Operations Omega
  }

